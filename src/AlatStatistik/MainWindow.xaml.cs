        private string TeksKeluaran()
        {
            var sb = new StringBuilder();
            sb.AppendLine("AlatStatistik — keluaran");
            sb.AppendLine(DateTime.Now.ToString("yyyy-MM-dd HH:mm"));
            sb.AppendLine(new string('=', 40));

            foreach (var entri in _keluaran)
            {
                sb.AppendLine();
                sb.AppendLine($"[{entri.Nomor}] {entri.Judul}  ({entri.Waktu})");
                sb.AppendLine(TeksHasil(entri.Blok, entri.Judul));
            }

            return sb.ToString();
        }

        
        
        
        private List<ResultBlock> SemuaBlok()
        {
            var semua = new List<ResultBlock>();
            foreach (var entri in _keluaran)
            {
                semua.Add(Blocks.Heading($"[{entri.Nomor}] {entri.Judul}  ·  {entri.Waktu}"));
                semua.AddRange(entri.Blok);
            }
            return semua;
        }

        
        
        
        private static string TeksHasil(List<ResultBlock> blok, string judul)
        {
            var sb = new StringBuilder();
            sb.AppendLine(judul);
            sb.AppendLine(new string('=', judul.Length));

            foreach (var b in blok)
            {
                switch (b.Kind)
                {
                    case BlockKind.Heading:
                        sb.AppendLine();
                        sb.AppendLine(b.Text);
                        break;

                    case BlockKind.Table:
                        if (!string.IsNullOrEmpty(b.Title)) sb.AppendLine(b.Title);
                        if (b.Columns.Count > 0) sb.AppendLine(string.Join("\t", b.Columns));
                        foreach (var baris in b.Rows) sb.AppendLine(string.Join("\t", baris));
                        if (!string.IsNullOrEmpty(b.Footnote)) sb.AppendLine(b.Footnote);
                        sb.AppendLine();
                        break;

                    case BlockKind.Rumus:
                        foreach (var r in b.RumusList)
                            sb.AppendLine($"{r.Nama}: {r.Bentuk}  ({r.LabelTahun})");
                        if (!string.IsNullOrEmpty(b.Text)) sb.AppendLine(b.Text);
                        break;

                    case BlockKind.Substitusi:
                        foreach (var l in b.Langkah)
                            sb.AppendLine($"{l.Uraian} {l.Hitungan}".Trim());
                        break;

                    case BlockKind.Note:
                        sb.AppendLine(b.Text);
                        break;

                    case BlockKind.Chart:
                        sb.AppendLine($"[grafik: {b.Chart?.Title ?? b.Title ?? b.Text}]");
                        break;
                }
            }

            return sb.ToString();
        }

        

