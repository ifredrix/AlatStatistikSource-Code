        private void BangunMenuAnalisis()
        {
            
            
            
            
            
            
            foreach (string kategori in AnalysisRunner.Kategori(_analisis))
            {
                var dalamKategori = _analisis.Where(s => s.Category == kategori && !s.IsML).ToList();
                if (dalamKategori.Count == 0) continue;

                var menu = new MenuItem { Header = kategori };

