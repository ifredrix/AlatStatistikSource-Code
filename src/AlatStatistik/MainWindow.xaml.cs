        private static Dataset MuatDenganPilihLembar(string path)
        {
            if (!BukuExcel.TampaknyaXlsx(path)) return DataImport.Load(path);

            var lembar = BukuExcel.DaftarSheet(path);
            if (lembar.Count <= 1) return BukuExcel.Baca(path);

            int? pilih = JendelaInput.Pilih(
                "Pilih lembar kerja",
                $"Berkas ini berisi {lembar.Count} lembar. Mana yang berisi datanya?",
                lembar);
            if (pilih is null) throw new InvalidDataException("Pemilihan lembar dibatalkan.");

            return BukuExcel.Baca(path, lembar[pilih.Value]);
        }

