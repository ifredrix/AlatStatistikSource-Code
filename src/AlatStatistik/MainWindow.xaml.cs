            => MessageBox.Show(ex.Message, judul, MessageBoxButton.OK, MessageBoxImage.Error);

        private void GridData_BeginningEdit(object sender, DataGridBeginningEditEventArgs e)
        {
            if (e.Row.Item is not DataRowView baris) { _nilaiSebelumEdit = null; return; }
            _nilaiSebelumEdit = baris[e.Column.DisplayIndex] as string;
        }

        private void GridData_CellEditEnding(object sender, DataGridCellEditEndingEventArgs e)
        {
            
            if (e.Row.Item is not DataRowView baris) return;
            if (GridData.ItemsSource is not DataView view) return;
            if (e.EditAction != DataGridEditAction.Commit) return;

            int rowIndex = -1;
            for (int i = 0; i < view.Count; i++)
            {
                if (ReferenceEquals(view[i], baris)) { rowIndex = i; break; }
            }
            if (rowIndex < 0) return;

            string? nilaiBaru = baris[e.Column.DisplayIndex] as string;
            string namaKolom = e.Column.Header?.ToString() ?? "";
            if (string.IsNullOrEmpty(namaKolom)) return;

            
            
            string? nilaiLama = _nilaiSebelumEdit;
            _nilaiSebelumEdit = null;

            Dispatcher.BeginInvoke(new Action(() =>
            {
                try
                {
                    _data.FromDataTable(view!.Table!);
                    InfoData.Text = $"{Path.GetFileName(_data.SourcePath ?? _data.Name)} — {_data.RowCount} baris × {_data.ColumnCount} variabel";

                    if (!string.Equals(nilaiLama ?? "", nilaiBaru ?? "", StringComparison.Ordinal))
                    {
                        _data.Riwayat.Add(new DataChange
                        {
                            Baris = rowIndex,
                            Kolom = namaKolom,
                            NilaiLama = nilaiLama,
                            NilaiBaru = nilaiBaru
                        });
                    }
                    SegarkanRiwayat();
                }
                catch (Exception ex)
                {
                    
                    
                    App.TulisLog(ex);
                }
            }));
        }

        
        private string? _namaVariabelSebelum;

        private void GridVariabel_BeginningEdit(object sender, DataGridBeginningEditEventArgs e)
        {
            _namaVariabelSebelum = e.Row.Item is Variable v ? v.Name : null;
        }

        private void GridVariabel_CellEditEnding(object sender, DataGridCellEditEndingEventArgs e)
        {
            if (e.EditAction != DataGridEditAction.Commit) return;
            if (e.Row.Item is not Variable v) return;

            
            
            
            
            
            string kolom = e.Column.Header?.ToString() ?? "";
            string? nilaiBaru = e.EditingElement switch
            {
                TextBox tb => tb.Text,
                ComboBox cb => cb.SelectedItem?.ToString(),
                _ => null
            };

            
            
            
            
            
            if (nilaiBaru == null)
            {
                TerapkanVariabel(v);
                return;
            }

            string? namaLama = _namaVariabelSebelum;
            _namaVariabelSebelum = null;

            switch (kolom)
            {
                case KeteranganKolomVariabel.Nama:
                    {
                        
                        if (string.IsNullOrWhiteSpace(nilaiBaru)) { TerapkanVariabel(v); return; }

                        
                        
                        
                        
                        
                        if (namaLama != null
                            && !string.Equals(namaLama, v.Name, StringComparison.Ordinal)
                            && string.Equals(v.Name, nilaiBaru, StringComparison.Ordinal))
                        {
                            v.Name = namaLama;
                        }

                        
                        if (!GantiNama(v, nilaiBaru)) TerapkanVariabel(v);
                        return;
                    }

                case KeteranganKolomVariabel.Label:
                    v.Label = nilaiBaru.Trim();
                    break;

                case KeteranganKolomVariabel.Desimal:
                    if (int.TryParse(nilaiBaru, out int dec)) v.Decimals = Math.Clamp(dec, 0, 10);
                    break;

                case KeteranganKolomVariabel.TingkatUkur:
                    if (Enum.TryParse<Measure>(nilaiBaru, out var m)) v.Measure = m;
                    break;
            }

            TerapkanVariabel(v);
        }

        private void TerapkanVariabel(Variable? fokus = null)
        {
            Dispatcher.BeginInvoke(new Action(() =>
            {
                
                
                
                
                try
                {
                    App.TulisJejak("TerapkanVariabel mulai");
                    DataImport.InferMeasures(_data);
                    GridData.ItemsSource = _data.ToDataTable().DefaultView;
                    InfoData.Text = $"{Path.GetFileName(_data.SourcePath ?? _data.Name)} — "
                                  + $"{_data.RowCount} baris × {_data.ColumnCount} variabel";
                    SegarkanRiwayat();

                    
                    
                    
                    
                    
                    
                    
                    
                    App.TulisJejak("TerapkanVariabel selesai");
                }
                catch (Exception ex)
                {
                    TampilkanGalat(ex, "Gagal menyegarkan tabel setelah perubahan variabel");
                }
            }));
        }

        
        

        private bool GantiNama(Variable v, string namaBaru)
        {
            string bersih = (namaBaru ?? "").Trim();
            if (bersih.Length == 0) return false;
            if (string.Equals(v.Name, bersih, StringComparison.Ordinal)) return false;

            int bentrok = _data.IndexOf(bersih);
            if (bentrok >= 0 && !ReferenceEquals(_data.Variables[bentrok], v))
            {
                MessageBox.Show($"Sudah ada variabel bernama '{bersih}'.\n"
                                + "Nama variabel harus berbeda satu sama lain; huruf besar/kecil "
                                + "tidak dibedakan (sama seperti lazimnya).",
                                "Nama kembar", MessageBoxButton.OK, MessageBoxImage.Information);
                return false;
            }

            
            
            var entri = _data.GantiNama(v.Name, bersih);
            if (entri == null) return false;

            TerapkanVariabel(v);
            return true;
        }

        private void GantiNamaKolom_Click(object sender, RoutedEventArgs e)
        {
            if (_data.IsEmpty) { MessageBox.Show("Belum ada data."); return; }

            var target = GridVariabel.SelectedItem as Variable;
            if (target == null)
            {
                string? dicari = JendelaInput.Teks("Ganti nama variabel",
                    "Nama variabel yang diganti.\nYang tersedia: " + string.Join(", ", _data.Names), "");
                if (string.IsNullOrWhiteSpace(dicari)) return;

                int i = _data.IndexOf(dicari);
                if (i < 0)
                {
                    MessageBox.Show($"Tidak ada variabel bernama '{dicari}'.",
                                    "Tidak ditemukan", MessageBoxButton.OK, MessageBoxImage.Warning);
                    return;
                }
                target = _data.Variables[i];
            }

            string? baru = JendelaInput.Teks("Ganti nama variabel",
                $"Nama baru untuk '{target.Name}':", target.Name);
            if (string.IsNullOrWhiteSpace(baru)) return;

            if (!GantiNama(target, baru)) return;

            
            GridVariabel.SelectedItem = target;
            GridVariabel.ScrollIntoView(target);
        }

        internal static string? CariBerkas(string folder, string nama)
        {
            var dir = new DirectoryInfo(AppDomain.CurrentDomain.BaseDirectory);
            while (dir != null)
            {
                string kandidat = Path.Combine(dir.FullName, folder, nama);
                if (File.Exists(kandidat)) return kandidat;

                
                kandidat = Path.Combine(dir.FullName, nama);
                if (File.Exists(kandidat) && string.Equals(dir.Name, folder, StringComparison.OrdinalIgnoreCase))
                    return kandidat;

                dir = dir.Parent;
            }
            return null;
        }

        
        
        
        
        
