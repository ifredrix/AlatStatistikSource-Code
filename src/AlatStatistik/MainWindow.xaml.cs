        private void SisipKolom_Click(object sender, RoutedEventArgs e)
        {
            if (_data.IsEmpty) { MessageBox.Show("Belum ada data. Buka berkas atau buat data baru lebih dulu."); return; }

            string usul = _data.NamaVariabelUnik("V" + (_data.ColumnCount + 1));
            var jawab = JendelaInput.VariabelBaru("Sisipkan variabel", usul);
            if (jawab == null) return;

            string nama = string.IsNullOrWhiteSpace(jawab.Value.Nama) ? usul : jawab.Value.Nama;
            var v = _data.TambahVariabel(nama, jawab.Value.Ukur);
            _data.Riwayat.Add(DataChange.Struktur($"Menambah variabel '{v.Name}' ({v.Measure})"));
            SegarkanTampilanData();
            SegarkanRiwayat();
        }

        private void HapusKolom_Click(object sender, RoutedEventArgs e)
        {
            if (_data.IsEmpty) { MessageBox.Show("Belum ada data."); return; }

            string daftar = string.Join(", ", _data.Names);
            string? nama = JendelaInput.Teks("Hapus variabel",
                "Nama variabel yang dihapus.\nYang tersedia: " + daftar, "");
            if (string.IsNullOrWhiteSpace(nama)) return;

            int i = _data.IndexOf(nama);
            if (i < 0)
            {
                MessageBox.Show($"Tidak ada variabel bernama '{nama}'.", "Tidak ditemukan",
                                MessageBoxButton.OK, MessageBoxImage.Warning);
                return;
            }

            string namaAsli = _data.Variables[i].Name;
            if (!_data.HapusVariabel(namaAsli))
            {
                MessageBox.Show("Variabel terakhir tidak boleh dihapus — tabel harus punya minimal satu kolom.",
                                "Tidak bisa dihapus", MessageBoxButton.OK, MessageBoxImage.Information);
                return;
            }

            _data.Riwayat.Add(DataChange.Struktur($"Menghapus variabel '{namaAsli}'"));
            SegarkanTampilanData();
            SegarkanRiwayat();
        }

