        private void GridData_AutoGeneratingColumn(object? sender, DataGridAutoGeneratingColumnEventArgs e)
        {
            if (e.Column is not DataGridTextColumn kolom) return;
            int idx = _data.IndexOf(e.PropertyName ?? "");
            var variabel = idx >= 0 && idx < _data.Variables.Count ? _data.Variables[idx] : null;
            kolom.Binding = new System.Windows.Data.Binding(e.PropertyName ?? "")
            {
                Converter = _penukarLabelNilai,
                ConverterParameter = variabel
            };
        }

        private void GridData_AutoGeneratedColumns(object? sender, EventArgs e)
            => TambahkanKolomNomorBaris();

        private void TambahkanKolomNomorBaris()
        {
            if (_kolomNomorBaris != null && GridData.Columns.Contains(_kolomNomorBaris)) return;

            var kolom = new DataGridTextColumn
            {
                Header = "",
                IsReadOnly = true,
                CanUserSort = false,
                CanUserReorder = false,
                CanUserResize = false,
