        }

        
        
        
        private Border BuatKartuKeluaran(EntriKeluaran entri)
        {
            var kartu = new Border
            {
                Style = (Style)FindResource("Kartu"),
                Margin = new Thickness(0, 0, 0, 12)
            };
            AutomationProperties.SetName(kartu, $"Keluaran {entri.Nomor}: {entri.Judul}");

            var isi = new DockPanel { LastChildFill = true };

            var kepala = new Border
            {
                Background = (Brush)FindResource("Panel2"),
                BorderBrush = (Brush)FindResource("Garis"),
                BorderThickness = new Thickness(0, 0, 0, 1),
                Padding = new Thickness(12, 8, 12, 8),
                Margin = new Thickness(-12, -12, -12, 10)
            };
            DockPanel.SetDock(kepala, Dock.Top);

            var barisKepala = new DockPanel { LastChildFill = true };

            var waktu = new TextBlock
            {
                Text = entri.Waktu,
                FontSize = 11,
                Foreground = (Brush)FindResource("TeksRedup"),
                VerticalAlignment = VerticalAlignment.Center,
                Margin = new Thickness(10, 0, 0, 0)
            };
            DockPanel.SetDock(waktu, Dock.Right);
            barisKepala.Children.Add(waktu);

            barisKepala.Children.Add(new TextBlock
            {
                Text = $"{entri.Nomor}. {entri.Judul}",
                FontWeight = FontWeights.SemiBold,
                Foreground = (Brush)FindResource("Aksen")
            });

            kepala.Child = barisKepala;
            isi.Children.Add(kepala);

            isi.Children.Add(ResultsRenderer.Render(entri.Blok));

            kartu.Child = isi;
            return kartu;
        }

        
        
        
