        private void HitungVariabel_Click(object sender, RoutedEventArgs e)
        {
            if (_data.IsEmpty) { BelumAdaData(); return; }

            var jendela = new JendelaHitung(_data) { Owner = this };
            if (jendela.ShowDialog() != true) return;

            _cadanganData = _data.Clone();

            try
            {
                var h = Ekspresi.Hitung(jendela.TeksEkspresi, _data);
                if (!h.Sukses)
                {
                    _cadanganData = null;
                    MessageBox.Show(h.Galat, "Ekspresi tidak bisa dipakai",
                                    MessageBoxButton.OK, MessageBoxImage.Warning);
                    return;
                }

                var nilai = h.Nilai
                    .Select(v => v.HasValue
                        ? v.Value.ToString("G12", System.Globalization.CultureInfo.InvariantCulture)
                        : null)
                    .ToList();

                int i = Bantu.TambahKolom(_data, jendela.NamaTujuan, nilai);
                string namaTerpasang = _data.Names[i];

                SegarkanTampilanData();
                TampilkanHasil(RingkasanHitung(jendela.TeksEkspresi, namaTerpasang, h), "Hitung variabel");
            }
            catch (Exception ex)
            {
                _cadanganData = null;
                TampilkanGalat(ex, "Hitung variabel gagal");
            }
        }

        private static List<ResultBlock> RingkasanHitung(string teks, string kolom, HasilHitung h)
        {
            var ci = System.Globalization.CultureInfo.InvariantCulture;
            var blok = new List<ResultBlock> { Blocks.Heading("Hitung variabel") };

            blok.Add(Blocks.Note($"Kolom **{kolom}** dibuat dari ekspresi `{teks}`."));

            int hilang = h.Nilai.Count(v => v is null);
            blok.Add(Blocks.Note($"{h.Nilai.Count} baris dihitung; {hilang} di antaranya kosong "
                                 + $"karena ada nilai hilang di variabel yang dipakai."));

            var baris = new List<List<string>>();
            int batas = Math.Min(10, h.Nilai.Count);
            for (int r = 0; r < batas; r++)
                baris.Add(new List<string> { (r + 1).ToString(ci), h.Nilai[r] is { } v ? v.ToString("G10", ci) : "(hilang)" });

            blok.Add(Blocks.Table("Sepuluh baris pertama",
                                  new[] { "Baris", kolom }, baris,
                                  h.Nilai.Count > batas ? $"Dan {h.Nilai.Count - batas} baris lagi." : null));

            var ada = h.Nilai.Where(v => v.HasValue).Select(v => v!.Value).ToList();
            if (ada.Count > 0)
                blok.Add(Blocks.Note($"Rerata {ada.Average():G8}, terkecil {ada.Min():G8}, terbesar {ada.Max():G8}."));

            return blok;
        }

